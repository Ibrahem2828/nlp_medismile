# src/symptom_understanding/patient_explanation.py
from __future__ import annotations


def generate_patient_explanation(
    diagnosis: str,
    severity: str,
    urgency: str,
) -> str:
    """
    Patient-friendly Arabic explanation based on severity/urgency.
    Avoids jargon and encourages appropriate care.
    """

    if urgency == "Urgent":
        return (
            "الأعراض الحالية تشير إلى حالة تحتاج متابعة فورية لدى طبيب الأسنان، خصوصاً مع وجود علامات عدوى أو ألم شديد."\
            " ننصحك بزيارة الطوارئ أو حجز أقرب موعد ممكن، وتجنب الضغط أو الحرارة على السن حتى الفحص."\
            " في حال ظهور تورم بالوجه أو صعوبة في البلع/التنفس، يجب التوجه للطوارئ مباشرة."
        )

    if severity == "Moderate":
        return (
            "يوجد مؤشرات التهاب في العصب أو تسوس عميق يسبب ألماً عند البارد/الحار أو الضغط."\
            " من الأفضل حجز موعد خلال أيام قليلة لعمل فحص وأشعة، مع استخدام مسكنات آمنة عند الحاجة."\
            " تجنب المهيجات مثل المشروبات شديدة السخونة/البرودة إلى أن يتم العلاج."
        )

    if severity == "Low":
        return (
            "الأعراض تبدو خفيفة حالياً وقد ترتبط بتسوس سطحي أو التهاب لثة بسيط."\
            " حافظ على التفريش والخيط مرتين يومياً، وتجنب الحلويات والحمضيات الزائدة."\
            " إذا زادت الأعراض أو ظهر تورم/نزيف مستمر، احجز موعداً للفحص."
        )

    return (
        "الأعراض غير واضحة تماماً حالياً، ويُفضل مراقبتها."\
        " إذا استمر الألم أو زادت حدته أو ظهر تورم/نزيف، يرجى حجز فحص لدى طبيب الأسنان."\
        " العناية اليومية الجيدة قد تساعد على تقليل التهيج حتى يتحدد السبب."
    )
